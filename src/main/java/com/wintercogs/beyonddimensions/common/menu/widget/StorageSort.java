/**
 * 存储界面的排序方式；声明顺序就是界面里的排列顺序
 */
public enum StorageSort
{
    NAME,           // 名称
    QUANTITY,       // 数量
    MODID,          // 模组ID
    CREATIVE_TAB,   // 创造模式标签页
    MAX_STACK,      // 最大堆叠数
    INSERTED_TIME,  // 存入时间
    MODIFIED_TIME,  // 变动时间
}
